function openNav() {
    document.getElementById(`sidenav`).style.width = `250px`;
    document.getElementById(`sidenav`).style.display = `block`;
}

function closeNav() {
    document.getElementById(`sidenav`).style.width = `0`;
}

function openPp() {
    document.getElementById(`ppcontainer`).style.visibility = `visible`;
}

function closePp() {
    document.getElementById(`ppcontainer`).style.visibility = `hidden`;
}

